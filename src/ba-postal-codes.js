function normalize(text) {
  return String(text || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9\s.]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

const INDEX = new Map();
for (const [k, v] of Object.entries(RAW)) {
  INDEX.set(normalize(k), v);
}

export function lookupBuenosAiresPostalCode(city, province = "Buenos Aires") {
  const prov = normalize(province);
  const isBA = prov.includes("buenos aires") || prov === "caba" || prov.includes("ciudad autonoma") || prov.includes("capital federal");
  if (!isBA) return null;
  const c = normalize(city);
  if (!c) return null;
  if (INDEX.has(c)) return INDEX.get(c);
  // try partial contains for longer names
  for (const [k, v] of INDEX.entries()) {
    if (k.length >= 4 && (c.includes(k) || k.includes(c))) return v;
  }
  return null;
}

export function postalSuggestions(province = "Buenos Aires") {
  const prov = normalize(province);
  const isBA = prov.includes("buenos aires") || prov === "caba" || prov.includes("ciudad autonoma") || prov.includes("capital federal");
  if (!isBA) return [];
  // return a curated set of common names for frontend hints
  return Object.entries(RAW).slice(0, 400).map(([city, cp]) => ({ city, cp }));
}
